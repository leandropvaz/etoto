namespace EToto.Web.Services;

public class LanguageService
{
    private string _currentLanguage = "pt-BR";

    public string CurrentLanguage => _currentLanguage;
    public bool IsPortuguese => _currentLanguage == "pt-BR";

    // Os idiomas que o seletor oferece. Fonte única: o LanguageSwitcher lê daqui.
    public static readonly string[] SupportedLanguages = { "pt-BR", "en-US", "es-ES", "it-IT" };

    public event Action? OnLanguageChanged;

    public void SetLanguage(string language)
    {
        if (_currentLanguage == language) return;
        _currentLanguage = language;
        OnLanguageChanged?.Invoke();
    }

    public string this[string key] => GetTranslation(key);

    private string GetTranslation(string key)
    {
        var dict = _currentLanguage switch
        {
            "en-US" => _en,
            "es-ES" => _es,
            "it-IT" => _it,
            _ => _pt,
        };
        // Chave sem tradução no idioma escolhido cai no português, não na chave
        // crua: uma tela meio traduzida é ruim, mas "ple.action.start" na cara do
        // operador é pior.
        if (dict.TryGetValue(key, out var value)) return value;
        return _pt.TryGetValue(key, out var pt) ? pt : key;
    }

